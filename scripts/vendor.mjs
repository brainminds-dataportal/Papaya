// Regenerates the third-party libraries in lib/ from the npm packages declared in package.json.
//
// usage: npm run vendor
//
// Notes:
//  * lib/ files are committed, so that debug pages (tests/debug_*.html) and builds do not depend on node_modules.
//  * The following lib/ files are NOT managed here (legacy or locally modified copies):
//      base64-binary.js, numerics.js, pako-inflate.js, gl-matrix.js, GLU.js

import { build } from 'esbuild';
import { readFileSync } from 'node:fs';
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const projectDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
//read package.json directly (some packages do not export it)
const packageVersion = (name) => JSON.parse(readFileSync(packageFile(name, 'package.json'), 'utf8')).version;
const packageFile = (name, file) => path.join(projectDir, 'node_modules', name, file);

const banner = (name) => `/* ${name} ${packageVersion(name)} -- generated by scripts/vendor.mjs, do not edit */\n`;

// libraries distributed as browser-ready scripts (exposing a global variable)
const copied = [
    { name: 'jquery', from: 'dist/jquery.js', to: 'lib/jquery.js' },
    { name: 'bowser', from: 'es5.js', to: 'lib/bowser.js' },
    { name: 'gifti-reader-js', from: 'release/current/gifti-reader.js', to: 'lib/gifti-reader.js' },
    { name: 'xss', from: 'dist/xss.js', to: 'lib/xss.js' },
];

// libraries bundled from their sources as an IIFE exposing a global variable:
//  * nifti-reader-js is distributed as ES modules only
//  * daikon release file is built for node (its modules are null when loaded in a browser),
//    its emscripten based decoders reference node builtins only in node specific code paths
const bundled = [
    { name: 'nifti-reader-js', entry: 'nifti-reader-js', globalName: 'nifti', to: 'lib/nifti-reader.js' },
    { name: 'daikon', entry: 'daikon/src/main.js', globalName: 'daikon', to: 'lib/daikon.js', external: ['fs', 'path', 'crypto'] },
];

for (const lib of copied) {
    const content = await readFile(packageFile(lib.name, lib.from), 'utf8');
    await writeFile(path.join(projectDir, lib.to), banner(lib.name) + content);
    console.log(`${lib.to} <- ${lib.name}@${packageVersion(lib.name)}`);
}

for (const lib of bundled) {
    await build({
        entryPoints: [lib.entry],
        external: lib.external ?? [],
        absWorkingDir: projectDir,
        bundle: true,
        format: 'iife',
        globalName: lib.globalName,
        platform: 'browser',
        target: 'es2017',
        banner: { js: banner(lib.name).trim() },
        outfile: path.join(projectDir, lib.to),
        logLevel: 'warning',
    });
    console.log(`${lib.to} <- ${lib.name}@${packageVersion(lib.name)} (bundled as global '${lib.globalName}')`);
}
